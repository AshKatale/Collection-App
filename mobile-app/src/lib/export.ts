import { Platform } from 'react-native';
import { Directory, File, Paths } from 'expo-file-system';
import * as Sharing from 'expo-sharing';
import { getApiBaseUrl, getAuthToken, http } from '@/api/client';
import { errorMessage } from '@/lib/format';

type Params = Record<string, string | number | undefined>;

/** Readable, filesystem-safe file name built from the report parameters (we never trust the server's name). */
function fileNameFor(params: Params, format: 'xlsx' | 'pdf'): string {
  const parts = [params.report, params.date, params.fy && `FY${params.fy}`, params.year, params.month, params.type, params.from, params.to, params.id]
    .filter((p) => p !== undefined && p !== '')
    .map((p) => String(p).replace(/[^a-zA-Z0-9_-]/g, ''));
  return `${parts.join('_') || 'report'}.${format}`;
}

const MIME = {
  pdf: 'application/pdf',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
} as const;

/** Where "Save to device" is offered: Android has no "Save to Files" in its share sheet (iOS does). */
export const canSaveToFolder = Platform.OS === 'android';

/**
 * Download a server-built report (xlsx | pdf) and open the phone's share sheet.
 * Reports are generated by the server so Marathi names and Indian number formats match the web app.
 */
export async function downloadReport(params: Params, format: 'xlsx' | 'pdf'): Promise<void> {
  const file = await fetchReport(params, format);
  if (!(await Sharing.isAvailableAsync())) throw new Error('Sharing is not available on this device');
  await Sharing.shareAsync(file.uri, {
    mimeType: MIME[format],
    UTI: format === 'pdf' ? 'com.adobe.pdf' : 'org.openxmlformats.spreadsheetml.sheet',
    dialogTitle: 'Share report',
  });
}

/**
 * Download the report and save it into a folder the user picks (Downloads, Documents, ...).
 * Returns false when the user closes the folder picker without choosing.
 */
export async function saveReportToFolder(params: Params, format: 'xlsx' | 'pdf'): Promise<boolean> {
  const file = await fetchReport(params, format);

  let folder: Directory;
  try {
    folder = await Directory.pickDirectoryAsync();
  } catch {
    return false; // cancelled
  }

  const out = folder.createFile(fileNameFor(params, format).replace(/\.(xlsx|pdf)$/, ''), MIME[format]);
  out.write(await file.bytes());
  return true;
}

/** Download the report into the app's cache and return it. Throws a readable error on failure. */
async function fetchReport(params: Params, format: 'xlsx' | 'pdf'): Promise<File> {
  const query: Record<string, string | number> = { format };
  for (const [k, v] of Object.entries(params)) if (v !== undefined && (v as unknown) !== '') query[k] = v;
  const qs = Object.entries(query)
    .map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(String(v))}`)
    .join('&');
  const url = `${getApiBaseUrl()}/reports/export?${qs}`;

  const dir = new Directory(Paths.cache, 'reports');
  dir.create({ idempotent: true, intermediates: true });
  // Explicit name + overwrite: downloading the same report twice must work
  const target = new File(dir, fileNameFor(params, format));

  let file: File;
  try {
    file = await File.downloadFileAsync(url, target, {
      headers: { Authorization: `Bearer ${getAuthToken() ?? ''}` },
      idempotent: true,
    });
  } catch (err: any) {
    // The native downloader only says "status 4xx/5xx". Ask the API the same question to get the real reason.
    try {
      await http.get('/reports/export', { params: query, responseType: 'text' });
    } catch (apiErr) {
      throw new Error(errorMessage(apiErr, 'Export failed'));
    }
    throw new Error(err?.message || 'Export failed');
  }

  if (!file.exists || (file.size ?? 0) === 0) throw new Error('The server returned an empty file');
  return file;
}
